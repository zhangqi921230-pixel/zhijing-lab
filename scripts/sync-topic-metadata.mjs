import { format } from "prettier";
import { writeFile } from "node:fs/promises";
import { subjects, lessons } from "../src/lessons.mjs";
import { explorations } from "../src/explorations.mjs";
const metadata = (list) =>
  list.map(({ id, subject, title, grade, tag, description }) => ({
    id,
    subject,
    title,
    grade,
    tag,
    description,
  }));
await writeFile(
  new URL("../src/topicMetadata.mjs", import.meta.url),
  await format(
    `// Generated by scripts/sync-topic-metadata.mjs; detailed lesson data stays lazy.\nexport const subjects=${JSON.stringify(subjects)};\nexport const lessons=${JSON.stringify(metadata(lessons))};\nexport const explorations=${JSON.stringify(metadata(explorations))};\n`,
    { parser: "babel" },
  ),
);
